import { FRAMEWORKS } from '../compliance/controls.js';

// Generates a Markdown compliance evidence artifact — suitable for auditors.
export function renderMarkdown(report) {
  const L = [];
  const date = new Date().toISOString().slice(0, 10);
  const hasCompliance = !!(report.compliance?.frameworks?.length);

  L.push(`# AI Governance Audit Report`);
  L.push('');
  L.push(`| Field | Value |`);
  L.push(`|-------|-------|`);
  L.push(`| Repository | \`${report.repo}\` |`);
  L.push(`| Generated | ${date} |`);
  L.push(`| AI surfaces found | ${report.surfaceCount} |`);
  if (report.acceleratedBy) L.push(`| Accelerated by | ${report.acceleratedBy} |`);
  if (hasCompliance) {
    L.push(`| Frameworks | ${report.compliance.frameworks.map(f => FRAMEWORKS[f] ?? f).join(', ')} |`);
  }
  L.push('');

  // Severity summary
  L.push('## Surface Summary');
  L.push('');
  L.push('| Severity | Count | Meaning |');
  L.push('|----------|-------|---------|');
  L.push(`| 🔴 Red | ${report.summary.red} | Unguarded output to user or irreversible action |`);
  L.push(`| 🟡 Amber | ${report.summary.amber} | Partial guardrail coverage |`);
  L.push(`| 🟢 Green | ${report.summary.green} | Guardrails present |`);
  L.push('');

  // Per-framework violation summary
  if (hasCompliance) {
    L.push('## Compliance Violation Summary');
    L.push('');
    L.push('| Framework | Errors | Warnings |');
    L.push('|-----------|--------|----------|');
    for (const fw of report.compliance.frameworks) {
      const v = report.compliance.violations[fw] ?? { error: 0, warning: 0 };
      const label = FRAMEWORKS[fw] ?? fw;
      L.push(`| ${label} | ${v.error} | ${v.warning} |`);
    }
    L.push('');

    // Per-framework detail sections
    for (const fw of report.compliance.frameworks) {
      const label = FRAMEWORKS[fw] ?? fw;
      L.push(`## ${label}`);
      L.push('');

      // Collect all violations for this framework across all surfaces
      const allViolations = [];
      for (const s of report.surfaces) {
        for (const v of (s.violations ?? [])) {
          if (v.framework === fw) allViolations.push({ surface: s, violation: v });
        }
      }

      if (!allViolations.length) {
        L.push('_No violations found for this framework._');
        L.push('');
        continue;
      }

      // Group by control ID
      const byControl = new Map();
      for (const { surface, violation } of allViolations) {
        if (!byControl.has(violation.id)) byControl.set(violation.id, { violation, surfaces: [] });
        byControl.get(violation.id).surfaces.push(surface);
      }

      for (const [, { violation, surfaces }] of byControl) {
        const badge = violation.level === 'error' ? '🔴' : '🟡';
        L.push(`### ${badge} ${violation.id} — ${violation.title.split(' — ')[1] ?? violation.title}`);
        L.push('');
        L.push(`> ${violation.description}`);
        L.push('');
        L.push('**Affected surfaces:**');
        L.push('');
        L.push('| File | Sink | Side Effects | Severity |');
        L.push('|------|------|-------------|----------|');
        for (const s of surfaces) {
          const sev = s.severity === 'red' ? '🔴' : s.severity === 'amber' ? '🟡' : '🟢';
          const se = s.sideEffects?.length ? s.sideEffects.join(', ') : '—';
          L.push(`| \`${s.file}\` | ${s.sink} | ${se} | ${sev} ${s.severity} |`);
        }
        L.push('');
      }
    }
  }

  // All surfaces detail table
  L.push('## All AI Surfaces');
  L.push('');
  L.push('| Severity | File | Provider | Sink | Confidence | Fallback | Validation | HITL | Error Isolation |');
  L.push('|----------|------|----------|------|-----------|---------|-----------|------|-----------------|');

  const order = { red: 0, amber: 1, green: 2 };
  const sorted = [...report.surfaces].sort((a, b) => order[a.severity] - order[b.severity]);

  for (const s of sorted) {
    const sev = s.severity === 'red' ? '🔴 red' : s.severity === 'amber' ? '🟡 amber' : '🟢 green';
    const g = s.guardrails;
    const tick = v => v === true ? '✓' : v === 'n/a' ? '—' : '✗';
    L.push(`| ${sev} | \`${s.file}\` | ${s.providerLabel} | ${s.sink} | ${tick(g.confidence)} | ${tick(g.fallback)} | ${tick(g.validation)} | ${tick(g.humanInLoop)} | ${tick(g.errorIsolation)} |`);
  }
  L.push('');

  // CI gate
  if (report.gate) {
    L.push('## CI Gate');
    L.push('');
    if (report.gate.passed) {
      L.push('✅ **Gate passed** — no red side-effectful surfaces found.');
    } else {
      L.push(`❌ **Gate failed** — ${report.gate.blocking} blocking surface(s) found.`);
    }
    L.push('');
  }

  L.push('---');
  L.push('_Generated by [aiglare](https://github.com/nugehs/aiglare)_');
  L.push('');

  return L.join('\n');
}
